// ── Helper: Search majors (fuzzy match) ──────
function searchMajors(query) {
  const q = query.toLowerCase().trim();
  if (!q) return MAJOR_LIST.slice(0, 20);
  return MAJOR_LIST.filter(m => m.toLowerCase().includes(q));
}
